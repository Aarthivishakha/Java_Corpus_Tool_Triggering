package com.pramora.testable.metrics;

/**
 * Small boundary-sensitive functions. Data for statement coverage (test completeness)
 * and branch coverage (logic error detection): off-by-one mutations on the boundaries
 * are only caught by tests that assert exact edge values.
 */
public class LogicLab {

    public int clamp(int value, int min, int max) {
        if (value < min) {
            return min;
        }
        if (value > max) {
            return max;
        }
        return value;
    }

    public boolean isLeapYear(int year) {
        if (year % 400 == 0) {
            return true;
        }
        if (year % 100 == 0) {
            return false;
        }
        return year % 4 == 0;
    }

    public String grade(int score) {
        if (score >= 90) {
            return "A";
        }
        if (score >= 80) {
            return "B";
        }
        if (score >= 70) {
            return "C";
        }
        return "F";
    }

    public int daysInMonth(int month, int year) {
        switch (month) {
            case 2:
                return isLeapYear(year) ? 29 : 28;
            case 4:
            case 6:
            case 9:
            case 11:
                return 30;
            default:
                if (month < 1 || month > 12) {
                    return -1;
                }
                return 31;
        }
    }
}
